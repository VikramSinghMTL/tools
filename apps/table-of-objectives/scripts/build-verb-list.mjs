// Regenerates src/verbs-en.js from WordNet's verb index.
//
//   npm install --no-save wordnet-db
//   node scripts/build-verb-list.mjs node_modules/wordnet-db/dict/index.verb
//
// Keeps single-word verbs only (multi-word entries like "look_up" are dropped).
import fs from 'node:fs';

const [indexPath] = process.argv.slice(2);
if (!indexPath) {
  console.error('Usage: node scripts/build-verb-list.mjs <path to WordNet dict/index.verb>');
  process.exit(1);
}

const verbs = fs
  .readFileSync(indexPath, 'utf8')
  .split('\n')
  .filter((line) => line && !line.startsWith(' ')) // Skip the licence header.
  .map((line) => line.split(' ')[0])
  .filter((word) => /^[a-z]+(-[a-z]+)?$/.test(word));

const out = `/*! Verb list derived from WordNet 3.1. WordNet 3.0 Copyright 2006 by Princeton University.
 * All rights reserved. See LICENSE-WordNet.txt for the full licence.
 * Generated by scripts/build-verb-list.mjs: do not edit by hand. */
export default ${JSON.stringify(verbs.join(' '))};
`;

fs.writeFileSync(new URL('../src/verbs-en.js', import.meta.url), out);
console.log(`Wrote ${verbs.length} verbs to src/verbs-en.js`);
